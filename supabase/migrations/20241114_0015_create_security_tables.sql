-- ============================================================================
-- 2. AUDIT_LOG TABLE
-- ============================================================================
-- Tracks all critical operation attempts (success and failures) for security investigation
-- Supports compliance auditing, abuse pattern detection, and incident investigation
-- RLS policy ensures users can only view own logs; admins can view all

CREATE TABLE IF NOT EXISTS public.audit_log (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  timestamp TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  event_type VARCHAR(50) NOT NULL,
  severity VARCHAR(20) DEFAULT 'INFO' NOT NULL,
  user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  subject_id UUID,
  subject_type VARCHAR(50),
  action TEXT,
  status VARCHAR(20) NOT NULL,
  error_code VARCHAR(50),
  error_message TEXT,
  context JSONB DEFAULT '{}'::JSONB,
  ip_address INET,
  user_agent TEXT,

  -- Constraints
  CONSTRAINT event_type_not_empty CHECK (event_type != ''),
  CONSTRAINT status_valid CHECK (status IN ('success', 'failure')),
  CONSTRAINT severity_valid CHECK (severity IN ('INFO', 'WARNING', 'ERROR', 'CRITICAL')),
  CONSTRAINT timestamp_not_future CHECK (timestamp <= CURRENT_TIMESTAMP)
);

-- Add documentation
COMMENT ON TABLE public.audit_log IS
'Audit trail for critical operations and security events.
Tracks both successes and failures to enable abuse pattern detection.
event_type values: exchange_request_created, exchange_accepted, exchange_canceled,
  exchange_completed, escrow_created, escrow_released, dispute_created, dispute_resolved,
  rating_created, rating_deleted, verification_failed, unauthorized_access_attempt, admin_action.
severity: INFO (normal operations), WARNING (failed verifications), ERROR (system failures),
  CRITICAL (unauthorized access attempts, admin misuse).
context JSONB stores additional data: {attempt_count, reason, additional_details}.';

COMMENT ON COLUMN public.audit_log.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.audit_log.timestamp IS 'When event occurred (defaults to now(), must be <= now())';
COMMENT ON COLUMN public.audit_log.event_type IS 'Type of event (50 char max, not empty)';
COMMENT ON COLUMN public.audit_log.severity IS 'Event severity: INFO, WARNING, ERROR, CRITICAL';
COMMENT ON COLUMN public.audit_log.user_id IS 'UUID of user who triggered event (nullable for anonymous attempts)';
COMMENT ON COLUMN public.audit_log.subject_id IS 'ID of resource being operated on (exchange_id, dispute_id, rating_id, etc.)';
COMMENT ON COLUMN public.audit_log.subject_type IS 'Type of subject (exchange, dispute, rating, user, toy, etc.)';
COMMENT ON COLUMN public.audit_log.action IS 'Human-readable action description (e.g., ''User requested exchange for toy'')';
COMMENT ON COLUMN public.audit_log.status IS 'Operation result: success or failure';
COMMENT ON COLUMN public.audit_log.error_code IS 'Error code if status=failure (42501, 402, INSUFFICIENT_FUNDS, etc.)';
COMMENT ON COLUMN public.audit_log.error_message IS 'Human-readable error message';
COMMENT ON COLUMN public.audit_log.context IS 'Additional structured data (JSONB): {attempt_count, ip_from_request, reason}';
COMMENT ON COLUMN public.audit_log.ip_address IS 'Client IP address (INET type for network operations)';
COMMENT ON COLUMN public.audit_log.user_agent IS 'Client user agent string (browser or mobile client)';

