-- 1. ADMIN_USERS TABLE
-- ============================================================================
-- Tracks verified administrators for secondary admin verification in critical operations
-- Prevents compromised JWT tokens from performing admin operations
-- RLS policy ensures only admins can insert/update, all admins can view for verification

CREATE TABLE IF NOT EXISTS public.admin_users (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID NOT NULL UNIQUE REFERENCES public.profiles(id) ON DELETE CASCADE,
  verified_at TIMESTAMP WITH TIME ZONE NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT verified_at_not_future CHECK (verified_at <= CURRENT_TIMESTAMP),
  CONSTRAINT is_active_not_null CHECK (is_active IS NOT NULL)
);

-- Add documentation
COMMENT ON TABLE public.admin_users IS
'Verified administrator records for secondary admin verification.
Prevents compromised JWT tokens from performing admin operations beyond RLS JWT validation.
Each user can have exactly one admin record (unique constraint on user_id).
verified_at is the timestamp when the admin was verified (used for audit trail).
is_active allows admins to be deactivated without deleting records.';

COMMENT ON COLUMN public.admin_users.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.admin_users.user_id IS 'UUID foreign key to profiles.id (UNIQUE - one admin record per user)';
COMMENT ON COLUMN public.admin_users.verified_at IS 'Timestamp when admin was verified (must be <= now())';
COMMENT ON COLUMN public.admin_users.is_active IS 'Boolean flag to deactivate admins without deleting record';
COMMENT ON COLUMN public.admin_users.created_at IS 'Timestamp when admin record was created';
COMMENT ON COLUMN public.admin_users.updated_at IS 'Timestamp when admin record was last updated';

-- Indexes on admin_users
CREATE INDEX IF NOT EXISTS idx_admin_users_user_id ON public.admin_users(user_id);
COMMENT ON INDEX idx_admin_users_user_id IS 'Lookup admin by user_id for verification';

CREATE INDEX IF NOT EXISTS idx_admin_users_is_active ON public.admin_users(is_active);
COMMENT ON INDEX idx_admin_users_is_active IS 'Filter active admins only';

CREATE INDEX IF NOT EXISTS idx_admin_users_verified_at ON public.admin_users(verified_at DESC);
