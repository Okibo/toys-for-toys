-- Function: revoke_consent
-- Revokes a consent record by setting revoked_at timestamp
-- Updates child consent_status to 'consent_revoked'
CREATE OR REPLACE FUNCTION public.revoke_consent(
  p_consent_id UUID,
  p_reason TEXT DEFAULT NULL
)
RETURNS BOOLEAN AS $$
DECLARE
  v_user_id UUID;
  v_child_ids UUID[];
BEGIN
  -- Check that consent exists
  IF NOT EXISTS (SELECT 1 FROM public.consent_records WHERE id = p_consent_id) THEN
    RAISE EXCEPTION 'Consent record % does not exist', p_consent_id;
  END IF;

  -- Get consent details
  SELECT user_id, child_ids INTO v_user_id, v_child_ids
  FROM public.consent_records
  WHERE id = p_consent_id;

  -- Update revoked_at timestamp
  UPDATE public.consent_records
  SET revoked_at = CURRENT_TIMESTAMP
  WHERE id = p_consent_id AND revoked_at IS NULL;

  -- Update child consent_status to 'consent_revoked' if this was child_data consent
  IF array_length(v_child_ids, 1) > 0 THEN
    UPDATE public.kids
    SET consent_status = 'consent_revoked'
    WHERE id = ANY(v_child_ids) AND parent_id = v_user_id;
  END IF;

  RETURN true;
END;
$$ LANGUAGE plpgsql;

