-- Function: get_child_consent_status
-- Returns: consent status, has_consent boolean, consent_record_id, consented_at timestamp
CREATE OR REPLACE FUNCTION public.get_child_consent_status(p_child_id UUID)
RETURNS TABLE(
  status VARCHAR,
  has_consent BOOLEAN,
  consent_record_id UUID,
  consented_at TIMESTAMP WITH TIME ZONE
) AS $$
BEGIN
  RETURN QUERY
  SELECT
    k.consent_status,
    (k.consent_status = 'consented')::BOOLEAN,
    cr.id,
    cr.timestamp
  FROM public.kids k
  LEFT JOIN public.consent_records cr
    ON cr.user_id = k.parent_id
    AND k.id = ANY(cr.child_ids)
    AND cr.consent_type = 'child_data'
    AND cr.revoked_at IS NULL
  WHERE k.id = p_child_id
  LIMIT 1;
END;
$$ LANGUAGE plpgsql STABLE;

