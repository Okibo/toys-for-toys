-- 1. CONSENT_RECORDS TABLE
-- ============================================================================
-- Stores audit trail of all parental consents with IP and user agent for GDPR compliance
-- Supports consent revocation via revoked_at (soft delete, not hard delete)
-- child_ids is UUID array containing consented child UUIDs (empty for marketing consents)

CREATE TABLE IF NOT EXISTS public.consent_records (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  consent_type VARCHAR(50) NOT NULL,
  child_ids UUID[] DEFAULT '{}',
  consent_text TEXT NOT NULL,
  ip_address INET,
  user_agent TEXT,
  timestamp TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  revoked_at TIMESTAMP WITH TIME ZONE,

  -- Constraints
  CONSTRAINT consent_type_valid CHECK (consent_type IN ('child_data', 'marketing')),
  CONSTRAINT timestamp_not_future CHECK (timestamp <= CURRENT_TIMESTAMP),
  CONSTRAINT revoked_after_granted CHECK (revoked_at IS NULL OR revoked_at >= timestamp)
);

