-- ============================================================================
-- 6. NOTES & DESIGN DECISIONS
-- ============================================================================
-- 1. IMMUTABLE AUDIT TRAIL:
--    - consent_records has no UPDATE policy (RESTRICTIVE)
--    - Corrections require INSERT of new record and REVOKE of old record
--    - Preserves full history for GDPR compliance
--
-- 2. SOFT DELETE VIA REVOKED_AT:
--    - revoked_at column allows consent tracking even after revocation
--    - Supports "user consent history" queries
--    - Hard DELETE only by service role for GDPR data purge
--
-- 3. CHILD_IDS ARRAY:
--    - UUID[] type stores multiple child IDs per consent record
--    - GIN index for efficient array containment queries (ANY operator)
--    - Empty array for marketing consents (no children involved)
--    - Validates all children belong to parent in log_consent()
--
-- 4. IP_ADDRESS & USER_AGENT:
--    - INET type for IP addresses (supports network operations)
--    - Captured for fraud detection and GDPR audit purposes
--    - Helps identify suspicious consent patterns
--    - Can be cleared in GDPR data purge workflows
--
-- 5. CONSENT_STATUS ON KIDS:
--    - Denormalized from consent_records for query performance
--    - Four states: pending_consent, consented, consent_revoked, scheduled_for_deletion
--    - Used to enforce data processing permissions at application layer
--    - Must be kept in sync with consent_records via triggers/application logic
--
-- 6. RLS SECURITY:
--    - Users can only SELECT own consent records (privacy)
--    - Admins can SELECT all for compliance auditing
--    - Only service role can INSERT/DELETE (prevents client forgery)
--    - No UPDATE policy (immutable audit trail)
--
-- 7. PERFORMANCE INDEXES:
--    - idx_consent_records_user_id: Fast user lookups (foreign key)
--    - idx_consent_records_timestamp_desc: Recent events first
--    - idx_consent_records_child_ids: GIN for array containment (child_ids = ANY(...))
--    - idx_consent_records_user_timestamp: Composite for user history
--    - idx_consent_records_revoked_at: Partial index (only revoked records)
--
-- 8. GDPR COMPLIANCE:
--    - Consent text stored with record (versioning)
--    - IP address and user agent for audit trail
--    - Soft delete via revoked_at (preserves history)
--    - get_child_consent_status() for checking processing permissions
--    - log_consent() and revoke_consent() for structured consent management
--
