-- Function: log_consent
-- Inserts a new consent record and returns the consent_id
-- Called by API/Edge Functions when parent gives consent
CREATE OR REPLACE FUNCTION public.log_consent(
  p_user_id UUID,
  p_consent_type VARCHAR,
  p_child_ids UUID[],
  p_consent_text TEXT,
  p_ip_address INET,
  p_user_agent TEXT
)
RETURNS UUID AS $$
DECLARE
  v_consent_id UUID;
BEGIN
  -- Validate consent_type
  IF p_consent_type NOT IN ('child_data', 'marketing') THEN
    RAISE EXCEPTION 'Invalid consent_type: %', p_consent_type;
  END IF;

  -- Validate user_id exists in profiles
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'user_id % does not exist in profiles', p_user_id;
  END IF;

  -- Validate all child_ids exist and belong to this user (if child_ids provided)
  IF array_length(p_child_ids, 1) > 0 THEN
    IF NOT EXISTS (
      SELECT 1
      FROM UNNEST(p_child_ids) AS child_id
      WHERE NOT EXISTS (
        SELECT 1 FROM public.kids WHERE id = child_id AND parent_id = p_user_id
      )
    ) THEN
      -- Only error if any child_id is invalid
      IF EXISTS (
        SELECT 1 FROM UNNEST(p_child_ids) AS child_id
        WHERE NOT EXISTS (
          SELECT 1 FROM public.kids WHERE id = child_id AND parent_id = p_user_id
        )
      ) THEN
        RAISE EXCEPTION 'One or more child_ids do not exist or do not belong to user %', p_user_id;
      END IF;
    END IF;
  END IF;

  -- Insert consent record
  INSERT INTO public.consent_records (
    user_id,
    consent_type,
    child_ids,
    consent_text,
    ip_address,
    user_agent
  ) VALUES (
    p_user_id,
    p_consent_type,
    p_child_ids,
    p_consent_text,
    p_ip_address,
    p_user_agent
  )
  RETURNING id INTO v_consent_id;

  -- Update child consent_status to 'consented' if child_data consent
  IF p_consent_type = 'child_data' AND array_length(p_child_ids, 1) > 0 THEN
    UPDATE public.kids
    SET consent_status = 'consented'
    WHERE id = ANY(p_child_ids) AND parent_id = p_user_id;
  END IF;

  RETURN v_consent_id;
END;
$$ LANGUAGE plpgsql;

