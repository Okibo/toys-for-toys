-- ============================================================================
-- TRIGGER: Update 'available' column in tickets table
-- ============================================================================
-- Automatically updates the available column whenever balance or frozen changes
-- This ensures available = balance - frozen is always in sync
-- Implemented as BEFORE UPDATE trigger to validate and compute before storing

CREATE OR REPLACE FUNCTION public.update_tickets_available()
RETURNS TRIGGER AS $$
BEGIN
  -- The 'available' column is GENERATED ALWAYS AS (balance - frozen) STORED
  -- PostgreSQL automatically computes this, so no manual update needed
  -- This trigger ensures updated_at is set on every update
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_tickets_available_trigger
BEFORE UPDATE ON public.tickets
FOR EACH ROW
EXECUTE FUNCTION public.update_tickets_available();

COMMENT ON FUNCTION public.update_tickets_available() IS 'Trigger function to update updated_at timestamp and validate available calculation on tickets changes';
COMMENT ON TRIGGER update_tickets_available_trigger ON public.tickets IS 'Ensures updated_at is set whenever balance or frozen changes';

