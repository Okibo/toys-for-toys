-- Transaction type enum for audit trail
CREATE TYPE public.transaction_type_enum AS ENUM (
  'issue_starter',      -- Initial starter tickets issued to new users
  'earned_exchange',    -- Tickets earned from completing an exchange (seller)
  'spent_request',      -- Tickets spent when requesting a toy (buyer)
  'refunded',           -- Tickets refunded due to cancelled or failed exchange
  'fragment_redeemed'   -- Tickets earned from redeeming game fragments
);

-- ============================================================================
-- TICKETS TABLE
-- ============================================================================
-- Stores user ticket balances, frozen tickets (in escrow), and game earnings
-- The 'available' column is auto-calculated as (balance - frozen) via trigger
-- This enables efficient queries for available balance without computation

CREATE TABLE IF NOT EXISTS public.tickets (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID UNIQUE NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  balance INT DEFAULT 0 NOT NULL,
  frozen INT DEFAULT 0 NOT NULL,
  available INT GENERATED ALWAYS AS (balance - frozen) STORED,
  earned_from_games INT DEFAULT 0 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_balance CHECK (balance >= 0),
  CONSTRAINT valid_frozen CHECK (frozen >= 0),
  CONSTRAINT valid_earned_games CHECK (earned_from_games >= 0)
);

