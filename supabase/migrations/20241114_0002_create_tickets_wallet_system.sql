-- ============================================================================
-- Notes:
-- ============================================================================
-- 1. RLS policies are NOT created in this migration. They will be added separately in:
--    supabase/migrations/rls_policies.sql
--
-- 2. The 'available' column in tickets is a GENERATED ALWAYS AS (STORED) column.
--    PostgreSQL automatically maintains this computed column.
--    The trigger only handles updated_at timestamp updates.
--
-- 3. Transaction log is designed to be append-only:
--    - INSERT: Allowed (audit trail creation)
--    - UPDATE: Allowed (for correcting notes, but not amount/type)
--    - DELETE: Should be prevented via RLS policies (no delete permission)
--
-- 4. Fragment precision: NUMERIC(3,2) allows values 0.00-9.99 with 2 decimal places
--    Examples: 0.25, 0.5, 0.75, 1.0, 1.5, 2.0, etc.
--    This supports the 4-fragments = 1-ticket conversion (0.25 per game × 4 = 1.0)
--
-- 5. Indexes are strategic for common query patterns:
--    - idx_tickets_user_id: Support "get ticket balance by user"
--    - idx_transaction_log_user_id: Support "get transaction history"
--    - idx_transaction_log_created_at: Support time-based sorting and range queries
--    - idx_game_fragments_kid_id: Support "get game earnings by kid"
--    - idx_game_fragments_timestamp: Support "recent games first" queries
--    - Composite indexes optimize common WHERE + ORDER BY patterns
--
-- 6. Constraints enforce business logic:
--    - balance >= 0: Prevent negative balances
--    - frozen >= 0: Prevent negative frozen amounts
--    - earned_from_games >= 0: Prevent negative game earnings
--    - fragments_earned > 0: Ensure positive game fragment contributions
--    - bonus_earned >= 0: Allow zero or positive bonuses
--
-- 7. Foreign keys with ON DELETE CASCADE ensure:
--    - When a profile is deleted, all tickets/transactions/fragments are deleted
--    - When a kid is deleted, all fragments for that kid are deleted
--    - Maintains referential integrity automatically
