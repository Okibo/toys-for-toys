-- Wishlists table indexes
-- Fast lookup of wishlist by kid_id (kid_id is already UNIQUE, provides primary index)
-- No additional index needed as UNIQUE constraint creates an index

-- Wishlist_items table indexes
-- Fast lookup of items in a specific wishlist, ordered by priority
CREATE INDEX IF NOT EXISTS idx_wishlist_items_wishlist_priority ON public.wishlist_items(wishlist_id, priority_order);

-- Fast lookup of items matching a specific toy (for toy deletion cascade or toy activity queries)
CREATE INDEX IF NOT EXISTS idx_wishlist_items_toy_id ON public.wishlist_items(toy_id);

-- Fast search of custom wishes by text (for searching/filtering wishlist)
CREATE INDEX IF NOT EXISTS idx_wishlist_items_custom_wish_text ON public.wishlist_items USING GIN(to_tsvector('english', custom_wish_text));

-- Matching_log table indexes
-- Fast lookup of all matches for a specific wishlist item, ordered by score (descending)
CREATE INDEX IF NOT EXISTS idx_matching_log_item_scored ON public.matching_log(wishlist_item_id, scored_at DESC);

-- Fast lookup of all times a specific toy was matched (for toy popularity/analytics)
CREATE INDEX IF NOT EXISTS idx_matching_log_toy_id ON public.matching_log(matched_toy_id);

