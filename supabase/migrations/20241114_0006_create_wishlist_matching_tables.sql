-- NOTES:
-- ============================================================================
-- 1. Wishlists Schema:
--    - One wishlist per kid (UNIQUE kid_id constraint)
--    - TIMESTAMP WITH TIME ZONE for all audit fields (timezone-aware for global platform)
--    - CASCADE DELETE: if kid is deleted, wishlist and all items are deleted
--
-- 2. Wishlist Items Constraints:
--    - toy_or_custom_wish_xor: Exactly one of toy_id or custom_wish_text must be non-null
--      * This is XOR logic: (A AND NOT B) OR (NOT A AND B)
--      * Ensures each wish is either a reference to existing toy OR custom text (not both)
--    - valid_custom_wish_text: Custom wishes must be 1-500 characters
--    - valid_category: Category preference max 255 characters
--    - valid_priority_order: Priority must be > 0 (positive integers only)
--    - valid_condition: Condition must be one of: 'any', 'like_new', 'good_plus', 'good'
--    - UNIQUE (wishlist_id, priority_order): Cannot have duplicate priorities in same wishlist
--      * Allows reordering without key violations by incrementing/decrementing priorities
--
-- 3. Matching Log:
--    - score NUMERIC(3, 2): Fixed-point decimal with 3 total digits, 2 decimal places
--      * Allows values from 0.00 to 99.99, but CHECK constraint limits to 0.00-1.00
--      * More precise than FLOAT; suitable for scoring algorithms
--    - scored_at: Timestamp when match was generated (for analytics/auditing)
--    - CASCADE DELETE: If wishlist_item or toy is deleted, matching_log records are deleted
--
-- 4. Trigger Functions:
--    - update_wishlists_updated_at(): Auto-sets updated_at to CURRENT_TIMESTAMP before UPDATE
--    - update_wishlist_items_updated_at(): Auto-sets updated_at to CURRENT_TIMESTAMP before UPDATE
--    - Triggers fire BEFORE UPDATE to capture the new timestamp
--
-- 5. Indexes Strategy:
--    - (wishlist_id, priority_order): Composite index for fast retrieval of items in a wishlist
--      * Supports queries like: SELECT * FROM wishlist_items WHERE wishlist_id = ? ORDER BY priority_order
--      * Also used for UNIQUE constraint enforcement
--    - toy_id: Single index for fast lookup of all wishlists containing a toy
--      * Used when a toy is deleted or for toy popularity analysis
--    - custom_wish_text (GIN + tsvector): Full-text search on custom wishes
--      * Enables efficient ILIKE or FTS queries on wish descriptions
--      * GIN index type optimal for text search
--    - (wishlist_item_id, scored_at DESC): Composite for fast retrieval of matches ordered by recency
--      * Supports queries like: SELECT * FROM matching_log WHERE wishlist_item_id = ? ORDER BY scored_at DESC
--      * DESC ordering optimizes for "get latest matches" queries
--    - matched_toy_id: Single index for fast lookup of all matches for a toy
--      * Used for toy activity/analytics queries
--
-- 6. Priority Order Design:
--    - Allows any positive integer (1, 2, 3... or 10, 20, 30...)
--    - Supports efficient reordering without renumbering all items
--    - Example: Can insert new item at priority 15 between 10 and 20 without shifting others
--    - UNIQUE constraint ensures no gaps in user-visible ordering
--    - Application layer can handle sorting/renumbering if needed
--
-- 7. Preference Filters:
--    - category_preference: Single category preference (e.g., "action_figures")
--    - tag_preferences: Array of tags for more flexible filtering (e.g., ARRAY['educational', 'outdoor'])
--    - condition_preference: Specifies desired toy condition (defaults to 'any')
--    - These fields guide the matching algorithm but are optional
--
-- 8. Matching Algorithm Notes:
--    - score NUMERIC(3, 2) precision allows fine-grained matching (0.01 increments)
--    - Algorithm can use category, tags, and condition to calculate score
--    - Multiple matches per wishlist_item allowed (one row per matched toy)
--    - Logs enable A/B testing of different matching strategies
