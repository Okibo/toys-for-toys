-- ============================================================================
-- WISHLISTS TABLE
-- ============================================================================
-- Stores one wishlist per kid (1:1 relationship with kids table)
-- Each kid can have multiple items in their wishlist via wishlist_items table
-- Relationship: One wishlists row per kid; many wishlist_items per wishlist

CREATE TABLE IF NOT EXISTS public.wishlists (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  kid_id UUID NOT NULL UNIQUE REFERENCES public.kids(id) ON DELETE CASCADE,  -- One wishlist per kid (UNIQUE constraint)

  -- Audit Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Add comprehensive comments for documentation
COMMENT ON TABLE public.wishlists IS 'One wishlist per kid. Stores the parent container for a kids wishes and preferences. One-to-one relationship with kids table via UNIQUE kid_id constraint.';
COMMENT ON COLUMN public.wishlists.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.wishlists.kid_id IS 'UUID FK to kids.id - the kid this wishlist belongs to. UNIQUE constraint ensures one wishlist per kid (CASCADE DELETE)';
COMMENT ON COLUMN public.wishlists.created_at IS 'Timestamp when wishlist was created (auto-set on INSERT)';
COMMENT ON COLUMN public.wishlists.updated_at IS 'Timestamp when wishlist was last updated (auto-set on INSERT and UPDATE)';

-- ============================================================================
-- WISHLIST_ITEMS TABLE
-- ============================================================================
-- Stores individual items in a kid's wishlist
-- Each item can reference either an existing toy (toy_id) or a custom text wish (custom_wish_text)
-- CHECK constraint ensures exactly one of these is provided (XOR logic)
-- priority_order determines the ranking of wishes (1 = most wanted, 2 = second, etc.)

CREATE TABLE IF NOT EXISTS public.wishlist_items (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  wishlist_id UUID NOT NULL REFERENCES public.wishlists(id) ON DELETE CASCADE,  -- Wishlist this item belongs to
  toy_id UUID REFERENCES public.toys(id) ON DELETE SET NULL,                   -- Reference to existing toy (nullable for custom wishes)

  -- Wish Content (Either toy_id OR custom_wish_text must be non-null)
  custom_wish_text TEXT,  -- Custom wish text entered by kid/parent (nullable for toy references)

  -- Preference Filters
  category_preference VARCHAR(255),  -- Preferred toy category (e.g., "action_figures", "puzzles", "board_games")
  tag_preferences TEXT[],            -- Array of preferred tags (e.g., ARRAY['educational', 'outdoor'])
  condition_preference VARCHAR(20) DEFAULT 'any',  -- Preferred toy condition: 'any', 'like_new', 'good_plus', 'good'

  -- Ordering
  priority_order INT NOT NULL,  -- Integer priority (1 = highest priority, ascending order)

  -- Audit Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT toy_or_custom_wish_xor CHECK (
    (toy_id IS NOT NULL AND custom_wish_text IS NULL) OR
    (toy_id IS NULL AND custom_wish_text IS NOT NULL)
  ),  -- Exactly one of toy_id or custom_wish_text must be provided (not both, not neither)
  CONSTRAINT valid_custom_wish_text CHECK (
    custom_wish_text IS NULL OR (LENGTH(custom_wish_text) > 0 AND LENGTH(custom_wish_text) <= 500)
  ),  -- Custom wish text must be 1-500 chars if provided
  CONSTRAINT valid_category CHECK (
    category_preference IS NULL OR (LENGTH(category_preference) > 0 AND LENGTH(category_preference) <= 255)
  ),  -- Category must be non-empty and <= 255 chars
  CONSTRAINT valid_priority_order CHECK (priority_order > 0),  -- Priority must be positive integer
  CONSTRAINT valid_condition CHECK (
    condition_preference IN ('any', 'like_new', 'good_plus', 'good')
  ),  -- Condition must be one of allowed enum values
  UNIQUE (wishlist_id, priority_order)  -- Unique: cannot have duplicate priority_orders in same wishlist
);

-- Add comprehensive comments for documentation
COMMENT ON TABLE public.wishlist_items IS 'Individual wish items in a kids wishlist. Each item references either an existing toy or a custom wish text. Enforced via XOR CHECK constraint: either toy_id OR custom_wish_text is non-null (but not both). Unique (wishlist_id, priority_order) ensures no duplicate priorities.';
COMMENT ON COLUMN public.wishlist_items.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.wishlist_items.wishlist_id IS 'UUID FK to wishlists.id - the wishlist this item belongs to (CASCADE DELETE)';
COMMENT ON COLUMN public.wishlist_items.toy_id IS 'UUID FK to toys.id - the toy being wished for. NULL if custom_wish_text is provided (SET NULL on toy deletion)';
COMMENT ON COLUMN public.wishlist_items.custom_wish_text IS 'Custom wish text (1-500 chars) for wishes not matching an existing toy. NULL if toy_id is provided';
COMMENT ON COLUMN public.wishlist_items.category_preference IS 'Optional preferred toy category (e.g., "action_figures", "board_games", "puzzles") - max 255 chars';
COMMENT ON COLUMN public.wishlist_items.tag_preferences IS 'Optional array of preferred tags (e.g., ARRAY[''educational'', ''outdoor''])';
