-- ============================================================================
-- MATCHING_LOG TABLE
-- ============================================================================
-- Stores the results of matching algorithm runs
-- Tracks which toys were suggested for each wishlist item and their match score (0.00-1.00)
-- Enables analysis of matching effectiveness and audit trail of recommendations

CREATE TABLE IF NOT EXISTS public.matching_log (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  wishlist_item_id UUID NOT NULL REFERENCES public.wishlist_items(id) ON DELETE CASCADE,  -- Item being matched
  matched_toy_id UUID NOT NULL REFERENCES public.toys(id) ON DELETE CASCADE,              -- Toy suggested as a match

  -- Matching Score
  score NUMERIC(3, 2) NOT NULL,  -- Match score between 0.00 and 1.00 (NUMERIC(3,2) allows exactly 2 decimal places)

  -- Audit Timestamps
  scored_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_score_range CHECK (score >= 0.00 AND score <= 1.00)  -- Score must be between 0.00 and 1.00
);

-- Add comprehensive comments for documentation
COMMENT ON TABLE public.matching_log IS 'Records matching algorithm results. Each row represents a toy that was scored/matched against a wishlist item. Score is NUMERIC(3, 2) representing 0.00 to 1.00. Enables analysis of matching effectiveness and provides audit trail.';
COMMENT ON COLUMN public.matching_log.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.matching_log.wishlist_item_id IS 'UUID FK to wishlist_items.id - the wish item being matched (CASCADE DELETE)';
COMMENT ON COLUMN public.matching_log.matched_toy_id IS 'UUID FK to toys.id - the toy that was scored as a match (CASCADE DELETE)';
COMMENT ON COLUMN public.matching_log.score IS 'Match score as NUMERIC(3, 2): ranges from 0.00 (no match) to 1.00 (perfect match). Enforced via CHECK constraint.';
COMMENT ON COLUMN public.matching_log.scored_at IS 'Timestamp when the match was scored by the algorithm';

-- ============================================================================
-- TRIGGER FUNCTION FOR UPDATED_AT TIMESTAMPS
-- ============================================================================

-- Auto-update wishlists.updated_at on any UPDATE to wishlists table
CREATE OR REPLACE FUNCTION public.update_wishlists_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Auto-update wishlist_items.updated_at on any UPDATE to wishlist_items table
CREATE OR REPLACE FUNCTION public.update_wishlist_items_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================================
-- TRIGGERS
-- ============================================================================

-- Trigger 1: Auto-update wishlists.updated_at on any modification
CREATE TRIGGER trg_update_wishlists_updated_at
BEFORE UPDATE ON public.wishlists
FOR EACH ROW
EXECUTE FUNCTION public.update_wishlists_updated_at();

-- Trigger 2: Auto-update wishlist_items.updated_at on any modification
CREATE TRIGGER trg_update_wishlist_items_updated_at
BEFORE UPDATE ON public.wishlist_items
FOR EACH ROW
EXECUTE FUNCTION public.update_wishlist_items_updated_at();

