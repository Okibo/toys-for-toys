-- ============================================================================
-- NOTIFICATION_PREFERENCES TABLE
-- ============================================================================
-- Stores per-user notification delivery preferences with JSONB channel/frequency configuration
-- Implements quiet hours for child-safe notification timing
-- One row per user (UNIQUE user_id constraint)

CREATE TABLE IF NOT EXISTS public.notification_preferences (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Key (UNIQUE: one preference set per user)
  user_id UUID NOT NULL UNIQUE REFERENCES public.profiles(id) ON DELETE CASCADE,

  -- Notification Type Preferences (JSONB with channel and frequency)
  -- Valid channel values: 'email', 'push', 'in_app'
  -- Valid frequency values: 'instant', 'daily_digest', 'weekly_digest', 'off'
  match_found JSONB NOT NULL DEFAULT '{"channel": "email", "frequency": "daily_digest"}',
  request_received JSONB NOT NULL DEFAULT '{"channel": "push", "frequency": "instant"}',
  exchange_status JSONB NOT NULL DEFAULT '{"channel": "push", "frequency": "instant"}',
  game_reward JSONB NOT NULL DEFAULT '{"channel": "in_app", "frequency": "instant"}',
  message_received JSONB NOT NULL DEFAULT '{"channel": "push", "frequency": "instant"}',
  delivery_confirmed JSONB NOT NULL DEFAULT '{"channel": "push", "frequency": "instant"}',
  dispute_opened JSONB NOT NULL DEFAULT '{"channel": "push", "frequency": "instant"}',

  -- Quiet Hours (optional time window to suppress non-critical notifications)
  quiet_hours_start TIME,
  quiet_hours_end TIME,

  -- Audit Timestamp
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_match_found CHECK (
    match_found ? 'channel' AND match_found ? 'frequency'
  ),
  CONSTRAINT valid_request_received CHECK (
    request_received ? 'channel' AND request_received ? 'frequency'
  ),
  CONSTRAINT valid_exchange_status CHECK (
    exchange_status ? 'channel' AND exchange_status ? 'frequency'
  ),
  CONSTRAINT valid_game_reward CHECK (
    game_reward ? 'channel' AND game_reward ? 'frequency'
  ),
  CONSTRAINT valid_message_received CHECK (
    message_received ? 'channel' AND message_received ? 'frequency'
  ),
  CONSTRAINT valid_delivery_confirmed CHECK (
    delivery_confirmed ? 'channel' AND delivery_confirmed ? 'frequency'
  ),
  CONSTRAINT valid_dispute_opened CHECK (
    dispute_opened ? 'channel' AND dispute_opened ? 'frequency'
  ),
  CONSTRAINT valid_quiet_hours CHECK (
    (quiet_hours_start IS NULL AND quiet_hours_end IS NULL) OR
    (quiet_hours_start IS NOT NULL AND quiet_hours_end IS NOT NULL AND quiet_hours_start < quiet_hours_end)
  )
);

