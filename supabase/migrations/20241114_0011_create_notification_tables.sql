-- ============================================================================
-- NOTES:
-- ============================================================================
-- 1. Soft Delete Strategy:
--    - notifications.deleted_at is NULL for active notifications
--    - Queries should filter: WHERE deleted_at IS NULL to exclude soft-deleted records
--    - Supports GDPR data deletion workflows and audit trails
--    - Index idx_notifications_not_deleted optimizes soft-delete queries
--
-- 2. JSONB Structure for Preferences:
--    - Each notification type has a JSONB column with "channel" and "frequency" keys
--    - Example: '{"channel": "push", "frequency": "instant"}'
--    - CHECK constraints validate both keys are present
--    - Application can extend with additional keys (e.g., "do_not_disturb", "quiet_hours")
--
-- 3. Quiet Hours Implementation:
--    - quiet_hours_start and quiet_hours_end are TIME values (24h format)
--    - Both must be set or both must be NULL (constraint valid_quiet_hours)
--    - If set, non-critical notifications suppressed outside quiet hours
--    - Example: quiet_hours_start = '22:00', quiet_hours_end = '08:00' (bedtime)
--
-- 4. Related Item References:
--    - related_toy_id and related_exchange_id are nullable FKs
--    - Allow notifications to be linked to toys/exchanges for context
--    - Useful for UI: "Show me all notifications about this toy"
--    - SET NULL on delete preserves notification history
--
-- 5. Notification Types:
--    - match_found: New toy match in wishlist (email/daily typical)
--    - request_received: Someone requested user's toy (push/instant critical)
--    - exchange_status: Status updates on user's exchanges (push/instant)
--    - game_reward: Game reward earned (in_app/instant)
--    - message_received: Chat message received (push/instant)
--    - delivery_confirmed: Delivery confirmed (push/instant)
--    - dispute_opened: Dispute opened on exchange (push/instant)
--
-- 6. Indexes Strategy:
--    - idx_notifications_user_id: FK index for basic user notifications queries
--    - idx_notifications_created_at: Time-based pagination
--    - idx_notifications_user_created: Composite for "user's recent notifications"
--    - idx_notifications_user_unread: Filtered index for unread count (very selective)
--    - idx_notifications_toy_id: Partial index for toy-related notifications
--    - idx_notifications_exchange_id: Partial index for exchange-related notifications
--    - idx_notifications_not_deleted: Partial index optimizes soft-delete queries
--
-- 7. RLS Policies:
--    - Will be created in separate migration: supabase/migrations/*_rls_policies.sql
--    - Policies ensure users can only see/modify their own notifications and preferences
--    - Child-safe: Parental controls enforced at application layer
--
-- 8. Foreign Keys:
--    - user_id: CASCADE DELETE (if user deleted, all notifications/preferences deleted)
--    - related_toy_id: SET NULL (preserve notification history if toy deleted)
--    - related_exchange_id: SET NULL (preserve notification history if exchange deleted)
--
-- 9. Performance Considerations:
--    - Unread notification count uses filtered index for fast DISTINCT queries
--    - Partial indexes (WHERE clauses) reduce index size and write overhead
--    - JSONB columns support efficient querying via @> operator
--    - Denormalization via is_read boolean avoids JSON parsing in WHERE clauses
--
-- 10. GDPR Compliance:
--     - Soft delete via deleted_at supports GDPR data retention policies
--     - Quiet hours respect child-safe notification timing requirements
--     - Preference storage allows users to control notification delivery
--
