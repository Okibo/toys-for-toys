-- ============================================================================
-- INDEXES - Strategic for query performance
-- ============================================================================

-- Notifications table indexes
-- Fast lookup of all notifications for a user (common query: "get my notifications")
CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON public.notifications(user_id);

-- Fast filtering notifications by creation date (pagination, recent notifications first)
CREATE INDEX IF NOT EXISTS idx_notifications_created_at ON public.notifications(created_at DESC);

-- Composite index: user_id + created_at (find user's recent notifications efficiently)
CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON public.notifications(user_id, created_at DESC);

-- Fast filtering unread notifications for a user (notification badge count)
CREATE INDEX IF NOT EXISTS idx_notifications_user_unread ON public.notifications(user_id, is_read) WHERE is_read = false;

-- Fast lookup of notifications related to a toy (show all notifications for toy)
CREATE INDEX IF NOT EXISTS idx_notifications_toy_id ON public.notifications(related_toy_id) WHERE related_toy_id IS NOT NULL;

-- Fast lookup of notifications related to an exchange (show all notifications for exchange)
CREATE INDEX IF NOT EXISTS idx_notifications_exchange_id ON public.notifications(related_exchange_id) WHERE related_exchange_id IS NOT NULL;

-- Fast soft-delete queries (exclude deleted notifications)
CREATE INDEX IF NOT EXISTS idx_notifications_not_deleted ON public.notifications(user_id, deleted_at) WHERE deleted_at IS NULL;

-- Notification preferences table
-- No additional indexes needed beyond user_id UNIQUE constraint (already indexed)

