-- Notification type enum for categorizing notifications
CREATE TYPE public.notification_type_enum AS ENUM (
  'match_found',        -- New toy match found in wishlist
  'request_received',   -- User received a new exchange request
  'exchange_status',    -- Update on exchange status (accepted, in_transit, etc.)
  'game_reward',        -- Game reward earned
  'message_received',   -- New chat message received
  'delivery_confirmed', -- Delivery confirmed in exchange
  'dispute_opened'      -- Dispute opened on exchange
);

-- ============================================================================
-- NOTIFICATIONS TABLE
-- ============================================================================
-- Stores all notifications for users with soft delete support
-- Implements GDPR-compliant notification logging with is_read tracking
-- Supports filtering by type and related items (toy, exchange)

CREATE TABLE IF NOT EXISTS public.notifications (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  related_toy_id UUID REFERENCES public.toys(id) ON DELETE SET NULL,
  related_exchange_id UUID REFERENCES public.exchanges(id) ON DELETE SET NULL,

  -- Notification Content
  type public.notification_type_enum NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL,

  -- Status & Metadata
  is_read BOOLEAN NOT NULL DEFAULT false,

  -- Audit & Lifecycle Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMP WITH TIME ZONE,  -- Soft delete for GDPR compliance

  -- Constraints
  CONSTRAINT valid_title CHECK (title <> ''),
  CONSTRAINT valid_body CHECK (body <> ''),
  CONSTRAINT valid_type CHECK (
    type IN ('match_found', 'request_received', 'exchange_status', 'game_reward',
             'message_received', 'delivery_confirmed', 'dispute_opened')
  )
);

