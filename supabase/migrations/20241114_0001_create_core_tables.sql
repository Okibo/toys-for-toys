-- ============================================================================
-- KIDS TABLE
-- ============================================================================
-- Stores child/dependent information for parents/guardians
-- Implements soft delete via status column for GDPR compliance

CREATE TABLE IF NOT EXISTS public.kids (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  parent_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  birthdate DATE,
  age_group public.age_group_enum GENERATED ALWAYS AS (
    CASE
      WHEN EXTRACT(YEAR FROM age(birthdate)) < 3 THEN '0-2'::public.age_group_enum
      WHEN EXTRACT(YEAR FROM age(birthdate)) < 6 THEN '3-5'::public.age_group_enum
      WHEN EXTRACT(YEAR FROM age(birthdate)) < 9 THEN '6-8'::public.age_group_enum
      WHEN EXTRACT(YEAR FROM age(birthdate)) < 12 THEN '9-11'::public.age_group_enum
      WHEN EXTRACT(YEAR FROM age(birthdate)) < 15 THEN '12-14'::public.age_group_enum
      ELSE '15+'::public.age_group_enum
    END
  ) STORED,
  interests TEXT[] DEFAULT ARRAY[]::TEXT[],
  allergies TEXT,
  status public.kid_status_enum DEFAULT 'active' NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_age_group CHECK (age_group IN ('0-2', '3-5', '6-8', '9-11', '12-14', '15+')),
  CONSTRAINT valid_status CHECK (status IN ('active', 'hidden', 'deleted')),
  CONSTRAINT valid_birthdate CHECK (birthdate <= CURRENT_DATE)
);

