-- ============================================================================
-- INDEXES
-- ============================================================================
-- Optimize queries on frequently filtered/joined columns

-- Index on kids.parent_id for efficient lookups of children by parent
CREATE INDEX IF NOT EXISTS idx_kids_parent_id ON public.kids(parent_id);

-- Index on kids.status for efficient soft delete queries (e.g., WHERE status = 'active')
CREATE INDEX IF NOT EXISTS idx_kids_status ON public.kids(status);

-- Composite index on parent_id and status for common query pattern
CREATE INDEX IF NOT EXISTS idx_kids_parent_status ON public.kids(parent_id, status);

-- Index on profiles.email for authentication lookups
CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);

-- ============================================================================
-- VIEW: user_age_groups
-- ============================================================================
-- Aggregates kids by age group for statistics and insights

CREATE OR REPLACE VIEW public.user_age_groups AS
SELECT
  k.parent_id,
  k.age_group,
  COUNT(k.id) AS child_count,
  ARRAY_AGG(k.id) FILTER (WHERE k.status = 'active') AS active_child_ids,
  COUNT(k.id) FILTER (WHERE k.status = 'active') AS active_count,
  COUNT(k.id) FILTER (WHERE k.status = 'hidden') AS hidden_count,
  COUNT(k.id) FILTER (WHERE k.status = 'deleted') AS deleted_count,
  MAX(k.updated_at) AS last_updated
FROM public.kids k
GROUP BY k.parent_id, k.age_group;

COMMENT ON VIEW public.user_age_groups IS 'Aggregated view of kids grouped by age_group per parent_id';

