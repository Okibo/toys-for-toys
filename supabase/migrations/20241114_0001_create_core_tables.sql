--
-- 3. Soft delete via status column allows GDPR data deletion workflows:
--    - status = 'active': Child visible to parent
--    - status = 'hidden': Child data preserved but not visible (parental choice)
--    - status = 'deleted': Child marked for permanent deletion (GDPR request)
--
-- 4. The user_age_groups view is useful for:
--    - Parent dashboard showing children by age group
--    - Admin analytics on platform age demographics
--    - Filtering toy recommendations by age appropriateness
--
-- 5. Indexes are strategic:
--    - idx_kids_parent_id: Fast lookup of children by parent (frequent query)
--    - idx_kids_status: Fast filtering by soft delete status
--    - idx_kids_parent_status: Composite for common "active children of parent" query
--    - idx_profiles_email: Support authentication lookups
