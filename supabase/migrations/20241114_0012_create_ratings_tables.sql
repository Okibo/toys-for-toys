-- ============================================================================
-- NOTES:
-- ============================================================================
-- 1. Ratings Constraints:
--    - rater_id != rated_user_id: Prevents users from rating themselves
--    - condition_rating BETWEEN 1 AND 5: 5-point scale enforced at DB layer
--    - communication_rating BETWEEN 1 AND 5: 5-point scale enforced at DB layer
--    - review_text length <= 500 chars: Application can display feedback on constraint violation
--    - exchange_id UNIQUE: Each exchange can have at most one rating
--
-- 2. User Stats Denormalization:
--    - total_exchanges: Count of distinct exchange_ids for the user
--    - avg_condition_rating: Average condition_rating across all ratings
--    - avg_communication_rating: Average communication_rating across all ratings
--    - avg_overall_rating: Average of (condition_rating + communication_rating) / 2
--    - review_count: Count of ratings where review_text IS NOT NULL
--    - Denormalized for query efficiency on user profiles/dashboards
--
-- 3. Trigger Strategy:
--    - AFTER INSERT: Create/update user_stats for rated_user_id
--    - AFTER DELETE: Recalculate user_stats (avg will drop if rating removed)
--    - AFTER UPDATE: Recalculate user_stats (for edited ratings)
--    - Uses UPSERT logic (INSERT ... ON CONFLICT) to handle missing user_stats rows
--    - NULL handling: Aggregates use COALESCE to handle empty result sets
--
-- 4. Performance Considerations:
--    - Indexes on rater_id and rated_user_id for fast FK lookups
--    - Composite index (rated_user_id, created_at) for "get user's ratings" queries
--    - updated_at index on user_stats for materialization tracking
--    - avg_* columns are NUMERIC(2,1) to store values like 4.5 with 1 decimal place
--
-- 5. Badge Computation:
--    - Badge logic (e.g., "Trusted Trader" if avg_overall_rating >= 4.5) is in API layer
--    - Database only stores raw ratings and computed averages
--    - Keeps database logic simple; business rules in application
--
-- 6. RLS Policies:
--    - Will be created in Task 2.9 (separate migration)
--    - Should prevent users from modifying others' ratings
--    - Should allow public read access to published ratings (user isolation by exchange)
--
-- 7. Testing Strategy:
--    - Test INSERT: Create rating, verify user_stats auto-created and updated
--    - Test DELETE: Delete rating, verify averages recalculated correctly
--    - Test UPDATE: Modify rating, verify stats reflect new values
--    - Test NULL handling: User with no ratings should have NULL avg values
--    - Test constraints: Attempt invalid rating values (0, 6), self-rating, >500 char review
--
-- 8. Data Integrity:
--    - Foreign key CASCADE DELETE on profiles ensures data cleanup on user deletion
--    - CASCADE DELETE on exchanges ensures rating removed if exchange deleted
--    - UNIQUE constraint on exchange_id prevents duplicate ratings
