-- ============================================================================
-- FUNCTION: Recalculate user statistics from ratings
-- ============================================================================
-- Called by INSERT/UPDATE/DELETE triggers to refresh aggregated metrics
-- Handles NULL values gracefully (COALESCE for aggregates)
-- Creates user_stats row if it doesn't exist (INSERT trigger scenario)

CREATE OR REPLACE FUNCTION public.recalculate_user_stats(p_user_id UUID)
RETURNS void AS $$
DECLARE
  v_total_exchanges INT;
  v_avg_condition NUMERIC(2, 1);
  v_avg_communication NUMERIC(2, 1);
  v_avg_overall NUMERIC(2, 1);
  v_review_count INT;
BEGIN
  -- Calculate aggregates from ratings where rated_user_id = p_user_id
  SELECT
    COUNT(DISTINCT exchange_id)::INT,
    ROUND(COALESCE(AVG(condition_rating), 0)::NUMERIC, 1)::NUMERIC(2, 1),
    ROUND(COALESCE(AVG(communication_rating), 0)::NUMERIC, 1)::NUMERIC(2, 1),
    COUNT(*) FILTER (WHERE review_text IS NOT NULL)::INT
  INTO
    v_total_exchanges,
    v_avg_condition,
    v_avg_communication,
    v_review_count
  FROM public.ratings
  WHERE rated_user_id = p_user_id;

  -- Calculate overall average as average of condition + communication
  IF v_total_exchanges > 0 THEN
    v_avg_overall := ROUND(((v_avg_condition + v_avg_communication) / 2.0)::NUMERIC, 1)::NUMERIC(2, 1);
  ELSE
    v_avg_condition := NULL;
    v_avg_communication := NULL;
    v_avg_overall := NULL;
  END IF;

  -- Insert or update user_stats row
  INSERT INTO public.user_stats (user_id, total_exchanges, avg_condition_rating, avg_communication_rating, avg_overall_rating, review_count, updated_at)
  VALUES (p_user_id, v_total_exchanges, v_avg_condition, v_avg_communication, v_avg_overall, v_review_count, CURRENT_TIMESTAMP)
  ON CONFLICT (user_id) DO UPDATE SET
    total_exchanges = EXCLUDED.total_exchanges,
    avg_condition_rating = EXCLUDED.avg_condition_rating,
    avg_communication_rating = EXCLUDED.avg_communication_rating,
    avg_overall_rating = EXCLUDED.avg_overall_rating,
    review_count = EXCLUDED.review_count,
    updated_at = EXCLUDED.updated_at;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION public.recalculate_user_stats(UUID) IS 'Recalculates aggregated user statistics from ratings. Called by triggers on INSERT/UPDATE/DELETE.';

-- ============================================================================
-- TRIGGER: Update user stats on rating INSERT
-- ============================================================================
-- Recalculates user_stats whenever a new rating is inserted
-- Handles creation of user_stats row if it doesn't exist

CREATE OR REPLACE FUNCTION public.trigger_update_user_stats_on_rating_insert()
RETURNS TRIGGER AS $$
BEGIN
  PERFORM public.recalculate_user_stats(NEW.rated_user_id);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_update_user_stats_on_rating_insert
AFTER INSERT ON public.ratings
FOR EACH ROW
EXECUTE FUNCTION public.trigger_update_user_stats_on_rating_insert();

COMMENT ON TRIGGER trigger_update_user_stats_on_rating_insert ON public.ratings IS 'Updates user_stats when a rating is inserted';

-- ============================================================================
-- TRIGGER: Update user stats on rating DELETE
-- ============================================================================
-- Recalculates user_stats when a rating is deleted
-- Ensures stats remain consistent after deletion

CREATE OR REPLACE FUNCTION public.trigger_update_user_stats_on_rating_delete()
RETURNS TRIGGER AS $$
BEGIN
  PERFORM public.recalculate_user_stats(OLD.rated_user_id);
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_update_user_stats_on_rating_delete
AFTER DELETE ON public.ratings
FOR EACH ROW
EXECUTE FUNCTION public.trigger_update_user_stats_on_rating_delete();

COMMENT ON TRIGGER trigger_update_user_stats_on_rating_delete ON public.ratings IS 'Updates user_stats when a rating is deleted';

-- ============================================================================
-- TRIGGER: Update user stats on rating UPDATE
-- ============================================================================
-- Recalculates user_stats when a rating is updated (ratings might be editable)
-- Only recalculates if the rated_user_id changes (unlikely but defensive)

CREATE OR REPLACE FUNCTION public.trigger_update_user_stats_on_rating_update()
RETURNS TRIGGER AS $$
BEGIN
  -- Recalculate for both old and new rated_user_id in case it changed (unlikely)
  IF OLD.rated_user_id != NEW.rated_user_id THEN
    PERFORM public.recalculate_user_stats(OLD.rated_user_id);
  END IF;
  PERFORM public.recalculate_user_stats(NEW.rated_user_id);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_update_user_stats_on_rating_update
AFTER UPDATE ON public.ratings
FOR EACH ROW
EXECUTE FUNCTION public.trigger_update_user_stats_on_rating_update();

COMMENT ON TRIGGER trigger_update_user_stats_on_rating_update ON public.ratings IS 'Updates user_stats when a rating is updated';

