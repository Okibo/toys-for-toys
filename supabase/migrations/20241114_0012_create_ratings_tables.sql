-- ============================================================================
-- RATINGS TABLE
-- ============================================================================
-- Stores ratings and reviews for completed exchanges (1:1 with exchanges)
-- Enables users to rate trading partners on communication and toy condition
-- Unique constraint on exchange_id prevents duplicate ratings per exchange

CREATE TABLE IF NOT EXISTS public.ratings (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  exchange_id UUID NOT NULL UNIQUE REFERENCES public.exchanges(id) ON DELETE CASCADE,
  rater_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  rated_user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,

  -- Rating Metrics (5-point scale)
  condition_rating INT NOT NULL,
  communication_rating INT NOT NULL,

  -- Review Text (max 500 chars, nullable)
  review_text TEXT,

  -- Audit Timestamp
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT rater_not_rated CHECK (rater_id != rated_user_id),
  CONSTRAINT valid_condition_rating CHECK (condition_rating BETWEEN 1 AND 5),
  CONSTRAINT valid_communication_rating CHECK (communication_rating BETWEEN 1 AND 5),
  CONSTRAINT valid_review_length CHECK (review_text IS NULL OR LENGTH(review_text) <= 500)
);

-- Add comprehensive comments for documentation
COMMENT ON TABLE public.ratings IS 'Ratings and reviews for completed exchanges. Enables users to rate trading partners on toy condition and communication.';
COMMENT ON COLUMN public.ratings.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.ratings.exchange_id IS 'UUID FK to exchanges.id (UNIQUE: one rating per exchange, CASCADE DELETE)';
COMMENT ON COLUMN public.ratings.rater_id IS 'UUID FK to profiles.id - user who created the rating (CASCADE DELETE)';
COMMENT ON COLUMN public.ratings.rated_user_id IS 'UUID FK to profiles.id - user being rated (CASCADE DELETE)';
COMMENT ON COLUMN public.ratings.condition_rating IS 'Toy condition rating (1-5 scale)';
COMMENT ON COLUMN public.ratings.communication_rating IS 'Trading partner communication rating (1-5 scale)';
COMMENT ON COLUMN public.ratings.review_text IS 'Optional review text (max 500 characters)';
COMMENT ON COLUMN public.ratings.created_at IS 'Timestamp when rating was created';

-- ============================================================================
-- USER_STATS TABLE
-- ============================================================================
-- Denormalized statistics for user ratings (computed via triggers)
-- Stores aggregated metrics for efficient dashboard and profile queries
-- Updated automatically whenever a rating is inserted, updated, or deleted

CREATE TABLE IF NOT EXISTS public.user_stats (
  -- Primary Key
  user_id UUID PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,

  -- Aggregated Metrics
  total_exchanges INT DEFAULT 0 NOT NULL,
  avg_condition_rating NUMERIC(2, 1),
  avg_communication_rating NUMERIC(2, 1),
  avg_overall_rating NUMERIC(2, 1),
  review_count INT DEFAULT 0 NOT NULL,

  -- Audit Timestamp
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_total_exchanges CHECK (total_exchanges >= 0),
  CONSTRAINT valid_review_count CHECK (review_count >= 0),
  CONSTRAINT valid_avg_condition CHECK (avg_condition_rating IS NULL OR (avg_condition_rating >= 1 AND avg_condition_rating <= 5)),
  CONSTRAINT valid_avg_communication CHECK (avg_communication_rating IS NULL OR (avg_communication_rating >= 1 AND avg_communication_rating <= 5)),
  CONSTRAINT valid_avg_overall CHECK (avg_overall_rating IS NULL OR (avg_overall_rating >= 1 AND avg_overall_rating <= 5))
);

