-- Strategic indexes for common query patterns and performance optimization
-- These indexes support the most frequent queries without creating excessive write overhead

-- Toys table indexes
-- Index on toys.user_id for efficient lookups of toys by user (lister)
CREATE INDEX IF NOT EXISTS idx_toys_user_id ON public.toys(user_id);

-- Index on toys.status for efficient soft delete queries (WHERE status = 'active')
CREATE INDEX IF NOT EXISTS idx_toys_status ON public.toys(status);

-- Index on toys.category for efficient category browsing
CREATE INDEX IF NOT EXISTS idx_toys_category ON public.toys(category);

-- GIN index on toys.tags for fast array searches (e.g., WHERE 'LEGO' = ANY(tags))
CREATE INDEX IF NOT EXISTS idx_toys_tags_gin ON public.toys USING GIN(tags);

-- Index on toys.created_at for sorting by newest listings
CREATE INDEX IF NOT EXISTS idx_toys_created_at ON public.toys(created_at DESC);

-- Composite index for common query pattern: user's active toys
CREATE INDEX IF NOT EXISTS idx_toys_user_status ON public.toys(user_id, status);

