-- ============================================================================
-- TOY_PHOTOS TABLE
-- ============================================================================
-- Stores metadata for toy photos stored in Supabase Storage
-- Photos themselves are stored in Supabase Storage, not as BLOBs in database
-- Maintains ordering for gallery display

CREATE TABLE IF NOT EXISTS public.toy_photos (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  toy_id UUID NOT NULL REFERENCES public.toys(id) ON DELETE CASCADE,
  storage_path TEXT NOT NULL,
  display_order INT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_storage_path CHECK (storage_path <> ''),
  CONSTRAINT valid_display_order CHECK (display_order >= 1)
);

-- Add comments for documentation
