COMMENT ON COLUMN public.toy_photos.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.toy_photos.toy_id IS 'UUID foreign key to toys.id (CASCADE DELETE)';
COMMENT ON COLUMN public.toy_photos.storage_path IS 'Supabase Storage path to the image file';
COMMENT ON COLUMN public.toy_photos.display_order IS 'Order for gallery display (1, 2, 3, ...)';
COMMENT ON COLUMN public.toy_photos.created_at IS 'Timestamp when photo was uploaded';

-- ============================================================================
-- TOY_VIEWS TABLE
-- ============================================================================
-- Stores toy view analytics for engagement tracking
-- Tracks both authenticated users and anonymous viewers
-- Used for popularity metrics and recommendation algorithms

CREATE TABLE IF NOT EXISTS public.toy_views (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  toy_id UUID NOT NULL REFERENCES public.toys(id) ON DELETE CASCADE,
  viewer_user_id UUID DEFAULT NULL REFERENCES public.profiles(id) ON DELETE SET NULL,
  viewed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Add comments for documentation
COMMENT ON TABLE public.toy_views IS 'Toy view analytics for engagement tracking and recommendations';
COMMENT ON COLUMN public.toy_views.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.toy_views.toy_id IS 'UUID foreign key to toys.id (CASCADE DELETE)';
COMMENT ON COLUMN public.toy_views.viewer_user_id IS 'UUID foreign key to profiles.id (nullable for anonymous views, SET NULL on delete)';
COMMENT ON COLUMN public.toy_views.viewed_at IS 'Timestamp when toy was viewed';

