-- Condition enum for toy state/quality (like_new, good, fair, poor)
CREATE TYPE public.condition_enum AS ENUM (
  'like_new',  -- Toy appears brand new, unused or barely used
  'good',      -- Toy is in good condition with minimal wear
  'fair',      -- Toy has visible wear but is fully functional
  'poor'       -- Toy has significant wear or minor damage but is still usable
);

-- Toy status enum for lifecycle management and soft delete
CREATE TYPE public.toy_status_enum AS ENUM (
  'pending_moderation',  -- Toy submitted but awaiting admin approval
  'active',              -- Toy is active and visible to other users
  'unavailable',         -- Toy is temporarily unavailable (in an active exchange)
  'delisted'             -- Toy has been soft-deleted by user or admin
);

-- ============================================================================
-- TOYS TABLE
-- ============================================================================
-- Stores toy listings created by users
-- Core table for the ticket economy's primary asset
-- Uses denormalized photos_count for query performance

CREATE TABLE IF NOT EXISTS public.toys (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT,
  category VARCHAR(50) NOT NULL,
  tags TEXT[] DEFAULT NULL,
  age_range TEXT[] DEFAULT NULL,
  condition public.condition_enum NOT NULL,
  status public.toy_status_enum NOT NULL DEFAULT 'pending_moderation',
  photos_count INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  moderation_notes TEXT DEFAULT NULL,

  -- Constraints
  CONSTRAINT valid_condition CHECK (condition IN ('like_new', 'good', 'fair', 'poor')),
  CONSTRAINT valid_status CHECK (status IN ('pending_moderation', 'active', 'unavailable', 'delisted')),
  CONSTRAINT valid_photos_count CHECK (photos_count >= 0),
  CONSTRAINT valid_name CHECK (name <> ''),
  CONSTRAINT valid_category CHECK (category <> '')
);

