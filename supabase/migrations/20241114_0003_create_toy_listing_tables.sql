-- ============================================================================
-- Notes:
-- ============================================================================
-- 1. RLS policies are NOT created in this migration. They will be added separately in:
--    supabase/migrations/rls_policies.sql
--
-- 2. Soft delete via status column:
--    - status = 'pending_moderation': Toy submitted but awaiting admin approval
--    - status = 'active': Toy visible to other users for exchange
--    - status = 'unavailable': Toy currently in an active exchange
--    - status = 'delisted': Toy soft-deleted by user or admin
--    - RLS policies and API layer should filter out 'delisted' toys from queries
--
-- 3. Denormalized photos_count:
--    - The photos_count column in toys table is denormalized for query performance
--    - Avoids expensive COUNT queries when fetching toy listings
--    - Application layer or triggers should keep this in sync with toy_photos table
--    - Consider using PostgreSQL trigger for automatic synchronization
--
-- 4. Photos stored in Supabase Storage:
--    - Images are NOT stored as BLOBs in the database
--    - Only storage paths are stored in toy_photos.storage_path
--    - This follows Supabase best practices for scalable media storage
--    - Supabase Storage has built-in RLS policies for secure access
--
-- 5. Toy_views for analytics:
--    - Tracks both authenticated and anonymous views
--    - viewer_user_id is nullable for anonymous/unauthenticated viewers
--    - Used for popularity metrics, trending recommendations, and engagement analysis
--    - High write volume table; consider archiving old views to improve performance
--
-- 6. Tag searches with GIN index:
--    - GIN index on tags enables fast array searches
--    - Query pattern: SELECT * FROM toys WHERE tags @> ARRAY['LEGO']::text[]
--    - GIN indexing is more efficient than BTREE for array searches
--
-- 7. Indexes are strategic for common patterns:
--    - idx_toys_user_id: Support "get my listings"
--    - idx_toys_status: Support "show active toys only"
--    - idx_toys_category: Support category browsing
--    - idx_toys_tags_gin: Support tag-based search
--    - idx_toys_created_at: Support "newest first" sorting
--    - idx_toys_user_status: Composite for "user's active toys"
--    - idx_toy_photos_toy_id: Support "get photos for toy"
--    - idx_toy_views_toy_id: Support "view count" analytics
--    - idx_toy_views_viewed_at: Support "trending" queries
--
-- 8. Foreign key constraints:
--    - toys -> profiles: ON DELETE CASCADE (if user deleted, toys deleted)
--    - toy_photos -> toys: ON DELETE CASCADE (if toy deleted, photos deleted)
--    - toy_views -> profiles: ON DELETE SET NULL (if viewer deleted, keep view record)
--    - toy_views -> toys: ON DELETE CASCADE (if toy deleted, views deleted)
--
-- 9. ENUM type usage:
--    - condition_enum ensures only valid toy conditions are stored
--    - toy_status_enum enforces strict status transitions
--    - CHECK constraints provide additional validation
--
-- 10. Array column usage:
--     - tags and age_range use PostgreSQL's native TEXT[] array type
--     - JSON arrays are NOT used for better performance and simpler querying
--     - Queryable with: 'value' = ANY(tags) or tags @> ARRAY['value']::text[]
