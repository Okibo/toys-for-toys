-- ============================================================================
-- DELIVERY_CONFIRMATIONS TABLE
-- ============================================================================
-- Tracks toy condition at delivery (1:1 relationship with exchanges)
-- Records physical inspection details for dispute prevention & resolution
-- Unique constraint ensures each exchange has at most one delivery confirmation

CREATE TABLE IF NOT EXISTS public.delivery_confirmations (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Key (unique: each exchange has exactly one delivery confirmation)
  exchange_id UUID NOT NULL UNIQUE REFERENCES public.exchanges(id) ON DELETE CASCADE,

  -- Delivery Details
  condition_received public.condition_enum NOT NULL,  -- Actual toy condition received
  photos_count INT NOT NULL DEFAULT 0,                 -- Count of photos uploaded as proof
  notes TEXT,                                          -- Detailed notes from recipient

  -- Confirmation Timestamp
  confirmed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_condition CHECK (
    condition_received IN ('like_listed', 'minor_wear', 'damage', 'missing_parts')
  ),
  CONSTRAINT valid_photos_count CHECK (photos_count >= 0),
  CONSTRAINT non_empty_notes CHECK (notes IS NULL OR notes <> '')
);

