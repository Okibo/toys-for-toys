-- Exchange status enum for lifecycle management
-- Defines valid states through the complete exchange workflow
CREATE TYPE public.exchange_status_enum AS ENUM (
  'pending_request',   -- Initial request from requester awaiting lister decision
  'accepted',          -- Lister has accepted the exchange request
  'in_transit',        -- Toy is being shipped to requester
  'delivered',         -- Toy has been received by requester (awaiting confirmation)
  'confirmed',         -- Delivery confirmed, exchange is verified and tickets ready to release
  'completed',         -- Exchange fully completed, tickets transferred and released from escrow
  'disputed',          -- Dispute has been opened during this exchange
  'auto_completed',    -- Exchange auto-completed after 48h timeout without confirmation
  'canceled'           -- Exchange was canceled (soft delete for audit trail)
);

-- Condition enum for delivery confirmation - tracks toy condition at delivery
CREATE TYPE public.condition_enum AS ENUM (
  'like_listed',       -- Toy matches listed condition exactly
  'minor_wear',        -- Minimal additional wear since listing
  'damage',            -- Noticeable damage not mentioned in listing
  'missing_parts'      -- Parts missing from the toy
);

-- Dispute status enum for resolution tracking
CREATE TYPE public.dispute_status_enum AS ENUM (
  'open',              -- Dispute recently created, awaiting admin review
  'admin_review',      -- Admin actively reviewing dispute
  'resolved',          -- Admin has made resolution decision
  'closed'             -- Dispute fully closed (resolution implemented)
);

-- ============================================================================
-- EXCHANGES TABLE
-- ============================================================================
-- Stores all exchange transactions (core of the ticket economy escrow system)
-- Implements soft delete via status='canceled' (no hard deletes for audit trail)
-- Tracks exchange lifecycle from request to completion
-- Timestamps mark critical state transitions for audit and analytics

CREATE TABLE IF NOT EXISTS public.exchanges (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys (all with CASCADE DELETE for data consistency)
  requester_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,  -- User requesting the toy
  lister_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,     -- User listing the toy
  toy_id UUID NOT NULL REFERENCES public.toys(id) ON DELETE CASCADE,             -- The toy being exchanged (immutable after creation)
  kid_for_id UUID NOT NULL REFERENCES public.kids(id) ON DELETE CASCADE,         -- Child the toy is intended for (requester's child)

  -- Exchange Status & Lifecycle
  status public.exchange_status_enum NOT NULL DEFAULT 'pending_request',

  -- User Communication
  requester_message TEXT,  -- Optional message from requester to lister (shown in request)

  -- Audit & Lifecycle Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  accepted_at TIMESTAMP WITH TIME ZONE,            -- When lister accepted the request
  delivery_confirmed_at TIMESTAMP WITH TIME ZONE,  -- When delivery was confirmed/verified
  completed_at TIMESTAMP WITH TIME ZONE,           -- When exchange was fully completed

  -- Constraints
  CONSTRAINT valid_status CHECK (
    status IN ('pending_request', 'accepted', 'in_transit', 'delivered', 'confirmed',
               'completed', 'disputed', 'auto_completed', 'canceled')
  ),
  CONSTRAINT requester_not_lister CHECK (requester_id != lister_id),  -- Prevent self-exchange
  CONSTRAINT non_empty_message CHECK (requester_message IS NULL OR requester_message <> '')
);

