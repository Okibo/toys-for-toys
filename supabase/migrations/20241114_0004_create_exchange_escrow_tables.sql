-- ============================================================================
-- DISPUTES TABLE
-- ============================================================================
-- Tracks disputes that arise during or after exchanges
-- Can only be created for exchanges with delivery confirmation (verified delivery required)
-- Implements dispute resolution workflow: open -> admin_review -> resolved -> closed

CREATE TABLE IF NOT EXISTS public.disputes (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  exchange_id UUID NOT NULL REFERENCES public.exchanges(id) ON DELETE CASCADE,  -- The disputed exchange
  reported_by_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,  -- User who reported issue

  -- Dispute Details
  reason VARCHAR(50) NOT NULL,      -- Category of dispute (damage, wrong_item, not_received, misrepresentation)
  description TEXT NOT NULL,        -- Detailed description of the issue
  status public.dispute_status_enum NOT NULL DEFAULT 'open',

  -- Admin Resolution
  admin_notes TEXT,                 -- Notes from admin during review process
  resolution VARCHAR(50),           -- Resolution outcome (refund, accepted, rejected, replacement)

  -- Audit Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_status CHECK (
    status IN ('open', 'admin_review', 'resolved', 'closed')
  ),
  CONSTRAINT valid_reason CHECK (reason <> ''),
  CONSTRAINT valid_description CHECK (description <> ''),
  CONSTRAINT non_empty_admin_notes CHECK (admin_notes IS NULL OR admin_notes <> ''),
  CONSTRAINT valid_resolution CHECK (
    resolution IS NULL OR resolution IN ('refund', 'accepted', 'rejected', 'replacement')
  )
);

