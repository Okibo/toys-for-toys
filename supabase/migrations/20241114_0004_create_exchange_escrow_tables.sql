-- ============================================================================
-- NOTES:
-- ============================================================================
-- 1. Exchange Lifecycle Transitions:
--    pending_request -> accepted -> in_transit -> delivered -> confirmed -> completed
--    Alternative: pending_request -> canceled (at any point)
--    Alternative: accepted -> canceled (both parties agree)
--    Alternative: any state -> auto_completed (48h timeout)
--    Alternative: any state -> disputed (if issues arise)
--
-- 2. Soft Delete Strategy:
--    - Exchanges use status='canceled' for soft delete instead of hard delete
--    - This preserves audit trail for fraud investigation and compliance
--    - All related records (delivery_confirmations, disputes) use CASCADE DELETE
--      so they are physically removed when exchange is deleted
--
-- 3. Immutability of toy_id:
--    - toy_id cannot be updated after exchange creation
--    - This is enforced at the application layer (no UPDATE on this column)
--    - Database enforces at app-level through migration
--
-- 4. Delivery Confirmation:
--    - Each exchange can have at most one delivery confirmation (UNIQUE exchange_id)
--    - Created when requester confirms receipt (status='delivered' -> 'confirmed')
--    - Captures toy condition and proof photos
--
-- 5. Disputes:
--    - Can be created for any exchange after delivery (when delivery_confirmation exists)
--    - Supports multiple dispute types: damage, wrong_item, not_received, misrepresentation
--    - Admin resolution workflow: open -> admin_review -> resolved -> closed
--
-- 6. Indexes Strategy:
--    - requester_id, lister_id, toy_id: FK columns indexed for JOIN performance
--    - status: indexed for soft delete and workflow filtering queries
--    - created_at: indexed for time-based pagination and analytics
--    - Composite indexes for common query patterns (requester+status, lister+status)
--    - All indexes chosen to minimize write overhead while maximizing read speed
--
-- 7. RLS Policies:
--    - Will be created in separate migration: supabase/migrations/*_rls_policies.sql
--    - Policies ensure users can only see/modify their own exchanges
--
-- 8. Constraints:
--    - requester_not_lister: Prevents a user from exchanging with themselves
--    - Valid status, condition, reason values: Enforced via CHECK constraints
--    - Non-empty strings: Enforced via CHECK constraints where required
--    - Photos count >= 0: Enforced for data sanity
