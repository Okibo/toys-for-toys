COMMENT ON TABLE public.delivery_confirmations IS 'Delivery confirmation records linked 1:1 to exchanges. Records toy condition and proof photos at delivery point.';
COMMENT ON COLUMN public.delivery_confirmations.id IS 'UUID primary key generated by uuid_generate_v4()';
