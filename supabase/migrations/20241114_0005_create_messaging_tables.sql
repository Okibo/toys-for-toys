-- Trigger 1: Check blocking status before allowing message insert
-- Prevents blocked users from communicating during exchanges
CREATE TRIGGER trg_check_message_blocked
BEFORE INSERT ON public.exchange_messages
FOR EACH ROW
EXECUTE FUNCTION public.check_message_blocked();

-- Trigger 2: Auto-flag suspicious messages before insert
-- Detects and flags phone numbers, addresses, and payment terms
CREATE TRIGGER trg_auto_flag_suspicious_messages
BEFORE INSERT ON public.exchange_messages
FOR EACH ROW
EXECUTE FUNCTION public.auto_flag_suspicious_messages();

