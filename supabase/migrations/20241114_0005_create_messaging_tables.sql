-- ============================================================================
-- EXCHANGE_MESSAGES TABLE
-- ============================================================================
-- Stores all messages exchanged between users during an active exchange
-- Implements soft delete via is_deleted_by_sender flag for message persistence
-- Tracks moderation flags for messages containing sensitive information
-- Relationship: Many messages per exchange (one exchange can have multiple messages)

CREATE TABLE IF NOT EXISTS public.exchange_messages (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  exchange_id UUID NOT NULL REFERENCES public.exchanges(id) ON DELETE CASCADE,  -- Exchange this message belongs to
  sender_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,     -- User sending the message

  -- Message Content
  content TEXT NOT NULL,  -- Message body (max 500 characters enforced via CHECK constraint)

  -- Moderation & Flags
  moderation_flag BOOLEAN NOT NULL DEFAULT false,  -- True if message needs admin review
  moderation_notes TEXT,                           -- Admin notes about moderation decision
  is_deleted_by_sender BOOLEAN NOT NULL DEFAULT false,  -- Soft delete flag (sender can hide their messages)

  -- Soft Delete Support
  deleted_at TIMESTAMP WITH TIME ZONE,  -- Timestamp when message was deleted (NULL if not deleted)

  -- Audit Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT valid_content_length CHECK (LENGTH(content) > 0 AND LENGTH(content) <= 500),
  CONSTRAINT non_empty_content CHECK (content <> ''),
  CONSTRAINT valid_moderation_notes CHECK (
    moderation_notes IS NULL OR (LENGTH(moderation_notes) > 0 AND LENGTH(moderation_notes) <= 1000)
  ),
  CONSTRAINT deleted_at_consistency CHECK (
    (is_deleted_by_sender = true AND deleted_at IS NOT NULL) OR
    (is_deleted_by_sender = false AND deleted_at IS NULL)
  )
);

