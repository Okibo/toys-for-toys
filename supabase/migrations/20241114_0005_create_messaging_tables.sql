-- TRIGGER FUNCTIONS FOR MESSAGING LOGIC
-- ============================================================================

-- TRIGGER FUNCTION 1: Check if sender is blocked by the other party in the exchange
-- Prevents messages if the recipient has blocked the sender
-- Fired BEFORE INSERT on exchange_messages
CREATE OR REPLACE FUNCTION public.check_message_blocked()
RETURNS TRIGGER AS $$
DECLARE
  v_exchange RECORD;
  v_is_blocked BOOLEAN;
BEGIN
  -- Get exchange details to determine who the recipient is
  SELECT requester_id, lister_id INTO v_exchange
  FROM public.exchanges
  WHERE id = NEW.exchange_id;

  -- Determine recipient: if sender is requester, recipient is lister (and vice versa)
  -- Check if recipient has blocked the sender
  SELECT EXISTS(
    SELECT 1 FROM public.blocklist
    WHERE blocker_id = (
      CASE
        WHEN NEW.sender_id = v_exchange.requester_id THEN v_exchange.lister_id
        ELSE v_exchange.requester_id
      END
    )
    AND blocked_id = NEW.sender_id
  ) INTO v_is_blocked;

  -- Raise exception if sender is blocked by recipient
  IF v_is_blocked THEN
    RAISE EXCEPTION 'Cannot send message: recipient has blocked you';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- TRIGGER FUNCTION 2: Auto-flag messages containing suspicious content
-- Detects phone numbers (7+ digits), address keywords, payment keywords, and sets moderation_flag
-- Also populates moderation_notes with reason for flagging
-- Fired BEFORE INSERT on exchange_messages
CREATE OR REPLACE FUNCTION public.auto_flag_suspicious_messages()
RETURNS TRIGGER AS $$
DECLARE
  v_content_lower TEXT;
  v_has_phone_number BOOLEAN := false;
  v_has_address BOOLEAN := false;
  v_has_payment_terms BOOLEAN := false;
  v_flags_found TEXT[] := ARRAY[]::TEXT[];
BEGIN
  v_content_lower := LOWER(NEW.content);

  -- Check for phone number pattern (7 or more consecutive digits)
  v_has_phone_number := (v_content_lower ~ '\d{7,}');
  IF v_has_phone_number THEN
    v_flags_found := array_append(v_flags_found, 'phone_number');
  END IF;

  -- Check for address keywords (street, avenue, road, etc.)
  v_has_address := (
    v_content_lower ~ '\b(street|avenue|road|lane|drive|boulevard|circle|court|way|place|address|zip|postal|state|city|county)\b'
  );
  IF v_has_address THEN
    v_flags_found := array_append(v_flags_found, 'address_keywords');
  END IF;

  -- Check for payment keywords (venmo, paypal, bank, account, credit card, etc.)
  v_has_payment_terms := (
    v_content_lower ~ '\b(venmo|paypal|bank|account|credit card|debit card|wire transfer|payment|bitcoin|crypto|pay me|cash app|google pay|apple pay)\b'
  );
  IF v_has_payment_terms THEN
    v_flags_found := array_append(v_flags_found, 'payment_keywords');
  END IF;

  -- If any flags were found, set moderation_flag and populate moderation_notes
  IF array_length(v_flags_found, 1) > 0 THEN
    NEW.moderation_flag := true;
    NEW.moderation_notes := 'Auto-flagged by system: ' || array_to_string(v_flags_found, ', ');
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

