--    - Directional: blocker_id -> blocked_id (A blocks B does not mean B blocks A)
--    - Prevents blocked users from sending messages during exchanges
--    - UNIQUE (blocker_id, blocked_id) ensures each pair can only block once
--    - blocker_not_self CHECK constraint prevents self-blocking
--
-- 3. Trigger Logic:
--    - check_message_blocked(): Prevents message INSERT if recipient has blocked sender
--      * Determines recipient based on exchange requester/lister roles
--      * Raises exception if blocking relationship found
--      * Fired BEFORE INSERT to fail fast
--
--    - auto_flag_suspicious_messages(): Auto-flags potentially unsafe messages
--      * Detects phone numbers: regex \d{7,} (7+ consecutive digits)
--      * Detects address keywords: street, avenue, road, lane, drive, boulevard, etc.
--      * Detects payment keywords: venmo, paypal, bank, credit card, crypto, etc.
--      * Sets moderation_flag = true and populates moderation_notes with reasons
--      * Multiple triggers can set flags (flags are cumulative)
--
-- 4. Moderation System:
--    - moderation_flag: Indicates message needs admin review
--    - moderation_notes: Contains auto-generated reason or admin decision notes
--    - Flagged messages are visible but marked for review by admin dashboard
