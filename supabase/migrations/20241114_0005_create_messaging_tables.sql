-- ============================================================================
-- BLOCKLIST TABLE
-- ============================================================================
-- Tracks blocked user relationships (blocking is directional: blocker -> blocked)
-- Prevents blocked users from sending messages to each other
-- Unique constraint ensures each blocker can only block each blocked user once

CREATE TABLE IF NOT EXISTS public.blocklist (
  -- Primary Key
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Foreign Keys
  blocker_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,  -- User doing the blocking
  blocked_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,  -- User being blocked

  -- Block Reason (optional)
  reason TEXT,  -- Optional reason for the block (e.g., "spam", "inappropriate behavior")

  -- Audit Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

  -- Constraints
  CONSTRAINT blocker_not_self CHECK (blocker_id != blocked_id),  -- Cannot block oneself
  CONSTRAINT valid_reason CHECK (reason IS NULL OR (LENGTH(reason) > 0 AND LENGTH(reason) <= 500)),
  UNIQUE (blocker_id, blocked_id)  -- Unique constraint: each user can only block another user once
);

-- Add comprehensive comments for documentation
COMMENT ON TABLE public.blocklist IS 'Directional blocking relationship between users. Prevents blocked users from messaging during exchanges. Unique constraint ensures (blocker_id, blocked_id) is unique.';
COMMENT ON COLUMN public.blocklist.id IS 'UUID primary key generated by uuid_generate_v4()';
COMMENT ON COLUMN public.blocklist.blocker_id IS 'UUID FK to profiles.id - user initiating the block (CASCADE DELETE)';
COMMENT ON COLUMN public.blocklist.blocked_id IS 'UUID FK to profiles.id - user being blocked (CASCADE DELETE)';
COMMENT ON COLUMN public.blocklist.reason IS 'Optional reason for blocking (max 500 chars)';
COMMENT ON COLUMN public.blocklist.created_at IS 'Timestamp when block was created';

